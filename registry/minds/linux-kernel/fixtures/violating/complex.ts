export function handleRequest(input: string): string {
  if (input.length > 0) {
    if (input.length > 1) {
      if (input.length > 2) {
        if (input.length > 3) {
          if (input.length > 4) {
            if (input.length > 5) return input;
          }
        }
      }
    }
  }
  return "empty";
}
